    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        // TODO add your handling code here:
    String quantityStr = txtorderquantity.getText();
    String productName = txtproductname.getText();
    String priceStr = txtproductprice.getText();
    String pid = txtcustemail.getText();  // Assuming pid is used somewhere else

    if (quantityStr.isEmpty() || productName.isEmpty() || priceStr.isEmpty()) {
        JOptionPane.showMessageDialog(null, "Please fill in all fields.");
        return;
    }

    int quantity;
    double price;

try {
    quantity = Integer.parseInt(quantityStr);
    price = Double.parseDouble(priceStr);
    if (quantity <= 0 || price < 0) {
        JOptionPane.showMessageDialog(null, "Quantity must be greater than 0 and price must be non-negative.");
        return;
    }
} catch (NumberFormatException e) {
    JOptionPane.showMessageDialog(null, "Please enter valid numbers for quantity and price.");
    return;
}

double subtotal = quantity * price;
s += subtotal;
tot = String.valueOf(s);

try (Connection con = ConnectionProvider.getCon()) {

    // Step 1: Check current stock
    int currentStock = 0;
    try (PreparedStatement ptStock = con.prepareStatement("SELECT Stock FROM products WHERE Name = ?")) {
        ptStock.setString(1, productName);
        ResultSet rs = ptStock.executeQuery();
        if (rs.next()) {
            currentStock = rs.getInt("Stock");
        } else {
            JOptionPane.showMessageDialog(null, "Product not found in inventory.");
            return;
        }
    }
    if (currentStock < quantity) {
        JOptionPane.showMessageDialog(null, "Not enough stock available.");
        return;
    }
    try (PreparedStatement pt2 = con.prepareStatement("INSERT INTO cart(pname, price, quantity, subtotal) VALUES (?, ?, ?, ?)")) {
        pt2.setString(1, productName);
        pt2.setDouble(2, price);
        pt2.setInt(3, quantity);
        pt2.setDouble(4, subtotal);
        int rowsAffected = pt2.executeUpdate();

        if (rowsAffected > 0) {
            JOptionPane.showMessageDialog(null, "Insertion successful");
            setVisible(false);
            jLabel15.setText(tot);
            setVisible(true);
            DefaultTableModel model=(DefaultTableModel) jTable1.getModel();
            refreshProductTable();
            refreshCustomerTable();

        } else {
            JOptionPane.showMessageDialog(null, "Insertion failed. No rows affected.");
        }
    }
    int newStock = currentStock - quantity;
    try (PreparedStatement pt3 = con.prepareStatement("UPDATE products SET Stock = ? WHERE Name = ?")) {
        pt3.setInt(1, newStock);
        pt3.setString(2, productName);
        pt3.executeUpdate();
    }

} catch (Exception e) {
    JOptionPane.showMessageDialog(null, "An error occurred: " + e.getMessage());
}
 
   
    }//GEN-LAST:event_jButton1ActionPerformed

    private void refreshCartTable() {
    DefaultTableModel model = (DefaultTableModel) jTable3.getModel();
    model.setRowCount(0); 
    try (Connection con = ConnectionProvider.getCon();
         PreparedStatement ps = con.prepareStatement("SELECT * FROM cart");
         ResultSet rs = ps.executeQuery()) {

        while (rs.next()) {
            Object[] row = {
                rs.getString("pname"),
                rs.getBigDecimal("price"),
                rs.getInt("quantity"),
                rs.getBigDecimal("subtotal")
            };
            model.addRow(row);
        }
    } catch (Exception e) {
        JOptionPane.showMessageDialog(null, "Error loading cart data: " + e.getMessage());
    }
}
