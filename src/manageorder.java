private void generatePDFInvoice(String email, String name, String total) {
    try {
        String fileName = "Bill_" + name + "_" + System.currentTimeMillis() + ".pdf";
        Document document = new Document(PageSize.A4, 30, 30, 30, 30);
        PdfWriter writer = PdfWriter.getInstance(document, new FileOutputStream(fileName));
        document.open();
        PdfContentByte canvas = writer.getDirectContent();
        Rectangle border = new Rectangle(document.getPageSize());
        border.setLeft(20);
        border.setRight(document.getPageSize().getWidth() - 20);
        border.setTop(document.getPageSize().getHeight() - 20);
        border.setBottom(20);
        border.setBorder(Rectangle.BOX);
        border.setBorderWidth(1);
        canvas.rectangle(border);
        Font titleFont = FontFactory.getFont(FontFactory.HELVETICA_BOLD, 20);
        Paragraph title = new Paragraph("Invoice", titleFont);
        title.setAlignment(Element.ALIGN_CENTER);
        document.add(title);
        Font small = new Font(Font.FontFamily.HELVETICA, 10);
        Paragraph date = new Paragraph("Date: " + new SimpleDateFormat("dd-MM-yyyy HH:mm:ss").format(new Date()), small);
        date.setAlignment(Element.ALIGN_RIGHT);
        document.add(date);
        Font regular = new Font(Font.FontFamily.HELVETICA, 12);
        document.add(new Paragraph("Customer Name: " + name, regular));
        document.add(new Paragraph("Customer Email: " + email, regular));
        document.add(new Paragraph(" "));
        PdfPTable table = new PdfPTable(4);
        table.setWidthPercentage(100);
        table.setSpacingBefore(10f);
        table.setSpacingAfter(10f);
        table.addCell("Product Name");
        table.addCell("Price");
        table.addCell("Quantity");
        table.addCell("Subtotal");
        Connection con = ConnectionProvider.getCon();
        Statement st = con.createStatement();
        ResultSet rs = st.executeQuery("SELECT * FROM cart");
        while (rs.next()) {
            table.addCell(rs.getString("pname"));
            table.addCell("₹" + rs.getString("price"));
            table.addCell(rs.getString("quantity"));
            table.addCell("₹" + rs.getString("subtotal"));
        }
        document.add(table);
        Font totalFont = FontFactory.getFont(FontFactory.HELVETICA_BOLD, 14);
        Paragraph totalPara = new Paragraph("Total Amount: ₹" + total, totalFont);
        totalPara.setAlignment(Element.ALIGN_RIGHT);
        document.add(totalPara);
        Paragraph footer = new Paragraph("Thank you for choosing Venus Engineering Works!", small);
        footer.setAlignment(Element.ALIGN_BASELINE);
        footer.setSpacingBefore(20);
        document.add(footer);

        document.close();
        JOptionPane.showMessageDialog(null, "PDF Invoice generated: " + fileName);

    } catch (Exception e) {
        JOptionPane.showMessageDialog(null, "PDF generation error: " + e.getMessage());
    }
}


